// Declaramos una variable llamada 'town' con let (su valor puede cambiar) y le asignamos "Centro"
let town ="Centro";
// Declaramos una constante llamada 'year' con const (su valor no puede cambiar) y le asignamos "2023"
const year ="2023";
// Imprime en la consola los valores actuales: "Centro" y "2023"
console.log(town, year);
// Reasignamos un nuevo valor a la variable 'town' ("Sur").
town = "Sur";
// Imprime en la consola los valores actualizados: "Sur" y "2023"
console.log(town, year);